# Даны два целых числа А и В (А < В). 
# Найти сумму всех целых чисел от А до В включительно (использовать оператор цикла).

A = int(input('Введите число A: '))
B = int(input('Введите число B (больше чем A): '))

sum = 0

for i in range(A, B + 1): # 1, 2, 3
    sum += i

print(f'Сумма всех чисел равна: {sum}')
