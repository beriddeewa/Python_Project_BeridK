# Даны два целых числа А и В (А < В)
# Вывести в порядке убывания все целые числа, расположенные между А и В (включая сами числа А и В),
# а также количество этих чисел (использовать оператор цикла).

A = int(input('Введите число А: '))
B = int(input('Введите число В (больше чем А): '))

kol = 0

print(f'Числа между {B} и {A} в порядке убывания:')

i = B

while i >= A:
    print(i)
    kol += 1
    i = i - 1

print(f'Количество этих чисел: {kol}')
