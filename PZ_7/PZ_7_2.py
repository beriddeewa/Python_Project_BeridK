# Дана строка-предложение. 
# Зашифровать ее, поместив вначале все символы, расположенные на четных позициях строки, 
# а затем, в обратном порядке, все символы, расположенные на нечетных позициях (например, строка «Программа» превратится в «ргамамроП»).

s = input("Введите строку: ")

even_chars = s[1::2]

odd_chars_reversed = s[::2][::-1]

encrypted = even_chars + odd_chars_reversed

print(encrypted)
