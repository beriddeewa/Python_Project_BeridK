# Дан первый член A и знаменатель D геометрической прогрессии.
# Сформировать и вывести список размера 10, 
# содержащий 10 первых членов данной прогрессии: A, A*D, A*D^2, A*D^3, ...

A = int(input('A = '))
D = int(input('D = '))

lst = []
for i in range(10):
    prog = A * (D**i)
    lst.append(prog)

print(lst)

