# Дано целое число N (1 < N < 26). 
# Вывести N первых прописных (то есть заглавных) букв латинского алфавита.

n = int(input('Введите число больше 1 < n < 26: '))

n = input('Введите число от 1 до 26: ')

while True:
    try:
        n = int(n) 
        
        if 1 < n < 26:  
            break       
        else:
            print('Ошибка: число должно быть больше 1 и меньше 26!')
            n = input('Попробуйте снова: ')
            
    except ValueError:
        print('Неправильно ввели число!')
        n = input('Введите целое число от 1 до 26: ')


i = 0              
code = ord('A')    

while i < n:
    print(chr(code), end=' ')  
    code += 1                  
    i += 1                   

