# Дано целое число. 
# Если оно является положительным, то прибавить к нему 20, в противном случае вычесть из него 5.

n = input('Введите число: ')

while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print('Неправильно ввели число!')
        n = input('Введите число: ')

if n >= 0:
    n = n + 20
elif n < 0:
    n = n - 5

print(n)
