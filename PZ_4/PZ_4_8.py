# Ввести N чисел
# Посчитать и вывести количество чисел, равных нулю.

N = int(input('Сколько чисел вы хотите ввести? '))
print(f'Пожалуйста, введите {N} чисел по очереди:')

kol = 0
i = 0

while i < N:
    chislo = float(input(f'Введите {i + 1}-е число: '))
    
    if chislo == 0:
        kol += 1
        
    i = i + 1

print(f'Количество чисел равных нулю: {kol} ')
