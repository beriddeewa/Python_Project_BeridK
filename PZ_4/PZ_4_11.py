# Посчитать и вывести количество элементов арифметической прогрессии, удовлетворяющих условию (10 < a_i < 30).

a1 = float(input('Введите первый член прогрессии (a1): '))
d = float(input('Введите шаг прогрессии (d): '))
n = int(input('Сколько элементов прогрессии проверить? '))

kol = 0
tekushiy = a1

for i in range(n):
    if 10 < tekushiy < 30:
        kol += 1
    
    tekushiy += d  

print(f'Количество элементов между 10 и 30: {kol}')
