# Дана арифметическая прогрессия (a_1=1, a_2=4, a_3=7, a_4=10, a_5=13, ...)
# Составить программу, которая каждый элемент прогрессии разделит на 2 и результат округлит до ближайшего целого.

n = int(input('Сколько элементов прогрессии вывести и округлить? '))

tekushiy = 1

i = 0

while i < n:
    delenie = tekushiy / 2
    okruglenie = round(delenie)
    
    print(f'Элемент {tekushiy} / 2 = {delenie} -> Округлённо: {okruglenie}')
    
    tekushiy += 3
    i = i + 1
